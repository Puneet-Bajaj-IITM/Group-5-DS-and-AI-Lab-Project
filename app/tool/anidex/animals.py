def _same(noun, names):
    """Breeds whose article title is the breed name (or listed in BREED_WIKI)."""
    return (noun, [(b, BREED_WIKI.get(b)) for b in names])


def _suffix(noun, names, suffix):
    """Breeds whose article title is "<breed> <suffix>", e.g. "Gir cattle"."""
    return (noun, [(b, f"{b} {suffix}") for b in names])


